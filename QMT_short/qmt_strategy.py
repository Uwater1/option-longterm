def _log(msg):
    ts = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    print(f"[QMT {ts}] {msg}")


def _state_path(today_str):
    return os.path.join(STATE_DIR, f"state_{today_str}.json")


def _load_state(today_str):
    p = _state_path(today_str)
    if os.path.exists(p):
        try:
            with open(p, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception as e:
            _log(f"state load failed: {e}")
    return {"positions": {}, "decided": {}}


def _save_state(today_str, state):
    try:
        os.makedirs(STATE_DIR, exist_ok=True)
        with open(_state_path(today_str), "w", encoding="utf-8") as f:
            json.dump(state, f, indent=2, default=str)
    except Exception as e:
        _log(f"state save failed: {e}")


def init(C):
    """QMT entry point: build option chain maps + state."""
    today = datetime.datetime.now().date()
    today_str = today.strftime("%Y%m%d")
    A = {}
    A["today"] = today_str
    A["options_map"] = {}
    A["tick"] = {}
    A["state"] = _load_state(today_str)
    if A["state"]["decided"] or A["state"]["positions"]:
        pos_str = ", ".join(f"{k}:{v.get('contract')}"
                            for k, v in A["state"]["positions"].items()) or "none"
        _log(f"state restored for {today_str}: "
             f"decided={A['state']['decided']} positions={pos_str}")
    A["entry_attempts"] = {}

    cfg = QMT_CONFIG.get("etfs", {})
    for etf_key, ecfg in cfg.items():
        underlying = ecfg["qmt_underlying"]
        opt_list = None
        for date_param in [today_str, underlying, ""]:
            for opttype in ["", "CALL", "PUT"]:
                try:
                    result = C.get_option_list(underlying, date_param, opttype, True)
                    if result and len(result) > 0:
                        opt_list = result
                        break
                except Exception:
                    pass
            if opt_list:
                break
        if not opt_list:
            _log(f"[{etf_key}] NO options returned by get_option_list")
            continue

        chain = {}
        for opt_code in opt_list:
            try:
                detail = C.get_option_detail_data(opt_code)
            except Exception:
                continue
            if not detail:
                continue
            expire_str = detail.get("ExpireDate", "")
            opt_type = str(detail.get("optType", "")).upper()
            strike = detail.get("OptExercisePrice", 0)
            if not expire_str or not strike or not opt_type:
                continue
            try:
                expire = datetime.datetime.strptime(str(expire_str)[:8], "%Y%m%d").date()
            except Exception:
                continue
            dte = (expire - today).days
            if dte < 1 or dte > 45:   # near month only
                continue
            key = (expire, float(strike))
            if key not in chain:
                chain[key] = {}
            if opt_type in ("C", "CALL"):
                chain[key]["C"] = opt_code
            elif opt_type in ("P", "PUT"):
                chain[key]["P"] = opt_code
        A["options_map"][etf_key] = chain
        _log(f"[{etf_key}] chain built: {len(chain)} (expiry,strike) pairs")

    C.A = A
    _log(f"init done. underlyings={list(A['options_map'].keys())}")
    _log(f"audit log -> {AUDIT_LOG_FILE}")
    _log(f"state dir -> {STATE_DIR}")


def _get_prev_context(C, index_code, seed_prev_close, seed_exp_bar_vol):
    """Fetch (prev_close, exp_bar_vol) from the index daily history via QMT.
    prev_close = last completed daily close; exp_bar_vol = mean(last 20
    daily volumes)/48. Falls back to baked seeds on any failure."""
    try:
        today_str = C.A["today"]
        start_dt = datetime.datetime.strptime(today_str, "%Y%m%d") - datetime.timedelta(days=45)
        start = start_dt.strftime("%Y%m%d")
        data = C.get_market_data_ex(
            ["close", "volume"], [index_code], period="1d",
            start_time=start, end_time=today_str)
        rows = data.get(index_code) if data else None
        if rows is None or len(rows) < 1:
            return seed_prev_close, seed_exp_bar_vol
        past_rows = []
        if hasattr(rows, "iterrows"):
            for idx, row in rows.iterrows():
                dt_s = str(idx).replace("-", "").replace(" ", "").replace(":", "")[:8]
                if dt_s < today_str:
                    past_rows.append((float(row["close"]), float(row["volume"])))
        else:
            vals = rows.values if hasattr(rows, "values") else rows
            for r in vals:
                past_rows.append((float(r[0]), float(r[1])))
            if len(past_rows) > 1:
                past_rows = past_rows[:-1]

        if len(past_rows) < 1:
            return seed_prev_close, seed_exp_bar_vol
        prev_close = past_rows[-1][0]
        vols = [r[1] for r in past_rows[-20:]]
        exp_bar_vol = (sum(vols) / len(vols)) / 48.0
        if prev_close <= 0 or exp_bar_vol <= 0:
            return seed_prev_close, seed_exp_bar_vol
        return prev_close, exp_bar_vol
    except Exception as e:
        _log(f"prev context fetch failed ({index_code}): {e}")
        return seed_prev_close, seed_exp_bar_vol


def _get_index_bars(C, index_code, n_bars=6):
    """Fetch today's first n five-minute bars of the index via QMT.
    Returns (op, hi, lo, cl, vol) or None. Bars must be END-timestamped
    (bar 5 closes at 10:00). Uses ContextInfo.get_market_data_ex if
    available, else falls back to get_local_data."""
    today_str = C.A["today"]
    try:
        start = today_str + "093000"
        end = today_str + "100000"
        data = C.get_market_data_ex(
            ["open", "high", "low", "close", "volume"],
            [index_code], period="5m", start_time=start, end_time=end)
        df_like = data.get(index_code) if data else None
        if df_like is None or len(df_like) < n_bars:
            return None
        rows = df_like[:n_bars]
        op = [float(r[0]) for r in rows.values] if hasattr(rows, "values") else None
        if op is None:
            return None
        hi = [float(r[1]) for r in rows.values]
        lo = [float(r[2]) for r in rows.values]
        cl = [float(r[3]) for r in rows.values]
        vol = [float(r[4]) for r in rows.values]
        return op, hi, lo, cl, vol
    except Exception as e:
        _log(f"index bars fetch failed ({index_code}): {e}")
        return None


def _pick_contract(A, etf_key, side, spot_price):
    """Strike/expiry selection.
    500ETF mode 'nearest': nearest strike in the front month.
    159915ETF mode 'vol_t1': liquid strikes only; approximate live by
    widest bid volume at entry time (T-1 volume unavailable)."""
    chain = A["options_map"].get(etf_key, {})
    if not chain:
        return None
    expiries = sorted({k[0] for k in chain.keys()})
    front = expiries[0]
    opt_type = "C" if side == "long" else "P"
    mode = QMT_CONFIG["etfs"][etf_key].get("strike_mode", "nearest")

    candidates = [(k[1], v.get(opt_type)) for k, v in chain.items()
                  if k[0] == front and v.get(opt_type)]
    if not candidates:
        return None
    if mode == "nearest":
        candidates.sort(key=lambda x: abs(x[0] - spot_price))
        return candidates[0][1]

    # vol_t1: rank by ask-side depth, fall back to nearest
    best = None
    best_depth = -1.0
    for strike, code in candidates:
        t = A["tick"].get(code)
        depth = t.get("a1_v", 0.0) if t else 0.0
        if depth > best_depth:
            best_depth = depth
            best = code
    if best is None or best_depth <= 0:
        candidates.sort(key=lambda x: abs(x[0] - spot_price))
        return candidates[0][1]
    return best


def _place_buy(C, code, price, remark):
    acct = QMT_CONFIG.get("account", "")
    passorder(50, 1101, acct, code, 14, round(price, 4), CONTRACTS_PER_TRADE,
              remark, 2, "", C)


def _place_sell(C, code, price, remark):
    acct = QMT_CONFIG.get("account", "")
    passorder(51, 1101, acct, code, 14, round(price, 4), CONTRACTS_PER_TRADE,
              remark, 2, "", C)


def _refresh_ticks(C, codes):
    if not codes:
        return
    try:
        tick = C.get_full_tick(codes)
    except Exception as e:
        _log(f"get_full_tick error: {e}")
        return
    if not tick:
        return
    now_ts = int(time.time())
    for sym, data in tick.items():
        if not data:
            continue
        ask_list = data.get("askPrice", [])
        bid_list = data.get("bidPrice", [])
        ask_vol = data.get("askVol", [])
        bid_vol = data.get("bidVol", [])
        a1 = float(ask_list[0]) if ask_list and ask_list[0] else 0.0
        b1 = float(bid_list[0]) if bid_list and bid_list[0] else 0.0
        a1_v = float(ask_vol[0]) if ask_vol and ask_vol[0] else 0.0
        b1_v = float(bid_vol[0]) if bid_vol and bid_vol[0] else 0.0
        C.A["tick"][sym] = {"a1": a1, "b1": b1, "a1_v": a1_v, "b1_v": b1_v, "time": now_ts}


def _frac_of_day(now_dt):
    """Fraction of the 10:00-14:35 holding window elapsed."""
    start = datetime.datetime.combine(now_dt.date(), DECISION_TIME)
    end = datetime.datetime.combine(now_dt.date(), EXIT_TIME)
    total = (end - start).total_seconds()
    el = (now_dt - start).total_seconds()
    return min(max(el / total, 0.0), 1.0)


def handlebar(C):
    A = getattr(C, "A", None)
    if A is None:
        return
    now = datetime.datetime.now()
    today_str = A["today"]
    if now.strftime("%Y%m%d") != today_str:
        return
    state = A["state"]

    # -- hard deadline: flatten everything --
    if now.time() >= HARD_DEADLINE:
        for etf_key, pos in list(state["positions"].items()):
            t = A["tick"].get(pos["contract"], {})
            px = t.get("b1", 0.0) or pos.get("entry_price", 0.0)
            if px > 0:
                try:
                    _place_sell(C, pos["contract"], px, f"{etf_key}_DEADLINE")
                    _log(f"[{etf_key}] DEADLINE close {pos['contract']} @ {px}")
                    audit_event("DEADLINE", etf_key, pos["contract"], px)
                except Exception as e:
                    _log(f"[{etf_key}] DEADLINE close FAILED: {e}")
            del state["positions"][etf_key]
        _save_state(today_str, state)
        return

    # keep quotes fresh for held positions
    held = [state["positions"][e]["contract"] for e in state["positions"]]
    _refresh_ticks(C, held)

    # -- 14:35 scheduled exit --
    if now.time() >= EXIT_TIME:
        for etf_key, pos in list(state["positions"].items()):
            t = A["tick"].get(pos["contract"], {})
            px = t.get("b1", 0.0)
            if px <= 0:
                continue
            try:
                _place_sell(C, pos["contract"], px, f"{etf_key}_EXIT1435")
                _log(f"[{etf_key}] 14:35 exit {pos['contract']} @ {px}")
                audit_event("EXIT1435", etf_key, pos["contract"], px)
                del state["positions"][etf_key]
            except Exception as e:
                _log(f"[{etf_key}] 14:35 exit FAILED: {e}")
        _save_state(today_str, state)
        return

    # -- stoploss monitor on open positions --
    for etf_key, pos in list(state["positions"].items()):
        t = A["tick"].get(pos["contract"], {})
        px = t.get("b1", 0.0)
        if px <= 0:
            continue
        if px > pos.get("peak", 0.0):
            pos["peak"] = px
        stop = trailing_stop_price(pos.get("peak", px), _frac_of_day(now))
        if px <= stop:
            try:
                _place_sell(C, pos["contract"], px, f"{etf_key}_STOP")
                _log(f"[{etf_key}] STOPLOSS {pos['contract']} px={px} stop={stop:.4f}")
                audit_event("STOP", etf_key, pos["contract"], px,
                            "stop=%.*f peak=%.*f" % (6, stop, 6, pos.get("peak", px)))
                del state["positions"][etf_key]
                state["decided"][etf_key] = "stopped"
            except Exception as e:
                _log(f"[{etf_key}] STOPLOSS sell FAILED: {e}")
    _save_state(today_str, state)

    # -- 10:00 decision + entry --
    if now.time() < DECISION_TIME:
        return
    cfg_all = QMT_CONFIG.get("etfs", {})
    printed = A.setdefault("decision_printed", set())
    # restart-safe dedup: never write a second DECISION line for today,
    # even if state/in-memory markers were lost (QMT re-init / restart)
    audited = A.setdefault("audited_today", _decisions_audited_today(today_str))
    for etf_key, ecfg in cfg_all.items():
        if etf_key in state["decided"]:
            # log once why nothing happens (earlier run today already decided)
            if etf_key not in printed:
                _log(f"[{etf_key}] already decided today "
                     f"({state['decided'][etf_key]}), no new decision")
                printed.add(etf_key)
            continue
        # safety: position exists but 'decided' marker was lost (state file
        # corruption / re-init) -> restore marker, never re-enter
        if etf_key in state["positions"]:
            state["decided"][etf_key] = state["positions"][etf_key]["side"]
            _log(f"[{etf_key}] open position "
                 f"{state['positions'][etf_key]['contract']} found, decision marker restored")
            continue
        if etf_key not in A["options_map"]:
            state["decided"][etf_key] = "no_chain"
            if etf_key not in printed:
                _log(f"[{etf_key}] skip: no option chain was built in init "
                     f"(check 'NO options returned' init messages)")
                printed.add(etf_key)
            continue

        bars = _get_index_bars(C, ecfg["index_code"], n_bars=6)
        if bars is None:
            _log(f"[{etf_key}] skip: index bars unavailable")
            state["decided"][etf_key] = "no_bars"
            audit_skip(etf_key, "no_bars")
            continue
        op, hi, lo, cl, vol = bars

        prev_close, exp_bar_vol = _get_prev_context(
            C, ecfg["index_code"],
            ecfg["prev_close_seed"], ecfg["exp_bar_vol_seed"])
        raw_feats = compute_raw_features(op, hi, lo, cl, vol,
                                         prev_close, exp_bar_vol,
                                         is_20pct=ecfg.get("is_20pct", False))
        if raw_feats is None:
            state["decided"][etf_key] = "bad_bars"
            audit_skip(etf_key, "bad_bars")
            continue

        composite, detail = compute_composite(ecfg, raw_feats)
        side = decide_side(composite, ecfg["z_th_long"], ecfg["z_th_short"])
        # console print exactly once per ETF per day, even if QMT re-inits
        if etf_key not in printed:
            _log_decision_block(etf_key, composite, detail, ecfg, side, now)
            printed.add(etf_key)
        if etf_key in audited:
            _log(f"[{etf_key}] DECISION already audited today "
                 f"(earlier run), not writing a duplicate line")
        else:
            audit_decision(etf_key, prev_close, exp_bar_vol, raw_feats,
                           composite, detail, ecfg["z_th_long"], ecfg["z_th_short"], side)
            audited.add(etf_key)
        state["decided"][etf_key] = side
        if side == "flat":
            _save_state(today_str, state)
            continue

        # late start: decision only happened after ENTRY_CUTOFF -> signal was
        # logged above for debugging, but no order may be placed
        if now.time() > ENTRY_CUTOFF:
            _log(f"[{etf_key}] decision at {now.strftime('%H:%M:%S')} is past "
                 f"ENTRY_CUTOFF {ENTRY_CUTOFF.strftime('%H:%M:%S')}: "
                 f"signal logged, NO order placed")
            audit_skip(etf_key, "late_entry")
            _save_state(today_str, state)
            continue

        # spot reference = ETF last price
        try:
            etf_tick = C.get_full_tick([ecfg["qmt_underlying"]])
            spot = float(etf_tick[ecfg["qmt_underlying"]]["lastPrice"])
        except Exception:
            spot = float(cl[-1])

        contract = _pick_contract(A, etf_key, side, spot)
        if not contract:
            _log(f"[{etf_key}] skip entry: no contract picked")
            audit_skip(etf_key, "no_contract")
            continue
        _refresh_ticks(C, [contract])
        t = A["tick"].get(contract, {})
        ask = t.get("a1", 0.0)
        if ask <= 0:
            _log(f"[{etf_key}] skip entry: no ask quote for {contract}")
            audit_skip(etf_key, "no_ask")
            continue
        cost = ask * CONTRACT_MULTIPLIER * CONTRACTS_PER_TRADE
        if cost > MAX_COST_PER_TRADE:
            _log(f"[{etf_key}] skip entry: cost {cost:.0f} > cap {MAX_COST_PER_TRADE:.0f}")
            audit_skip(etf_key, "cost_cap")
            continue
        try:
            _place_buy(C, contract, ask + PRICE_TICK, f"{etf_key}_ENTRY_{side.upper()}")
            state["positions"][etf_key] = {
                "contract": contract, "side": side, "entry_price": ask,
                "peak": ask, "entry_time": now.strftime("%H:%M:%S"),
                "composite": composite,
            }
            _log(f"[{etf_key}] BUY {contract} ({side}) @ {ask}")
            audit_entry(etf_key, contract, side, ask, ask + PRICE_TICK, composite)
        except Exception as e:
            _log(f"[{etf_key}] entry FAILED: {e}")
        _save_state(today_str, state)
