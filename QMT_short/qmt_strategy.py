def _sign_f(x):
    if x > 0.0:
        return 1.0
    if x < 0.0:
        return -1.0
    return 0.0


def compute_raw_features(op, hi, lo, cl, vol, prev_close, exp_bar_vol,
                         is_20pct=False):
    """Compute all 24 raw base features for one morning session.

    op/hi/lo/cl/vol: length-6 arrays (index 5m bars 0..5).
    prev_close: yesterday's index close. exp_bar_vol: expected per-bar
    volume = mean(last 20 index daily volumes) / 48.
    Returns dict name -> float32.

    Note: rbreaker_sell_setup_proximity_early uses sell_setup = 0.0 and
    atr14_prev = prev_close * 0.02 because the offline pipeline's ctx
    lookup for those keys always falls back to these defaults
    (build_features.py lines 1045-1054).
    """
    op = np.asarray(op, dtype=np.float64)
    hi = np.asarray(hi, dtype=np.float64)
    lo = np.asarray(lo, dtype=np.float64)
    cl = np.asarray(cl, dtype=np.float64)
    vol = np.asarray(vol, dtype=np.float64)
    prev_close = np.float32(prev_close)
    exp_bar_vol = np.float32(exp_bar_vol)

    n = len(op)
    out = {}
    if n < 1 or prev_close <= 0.0 or exp_bar_vol <= 0.0:
        return None

    # EARLY_EXTRA ports consume float32 inputs (features_extra.py casts to
    # float32 before dispatch); base features stay float64.
    op64, hi64, lo64, cl64 = op, hi, lo, cl
    op = op.astype(np.float32)
    hi = hi.astype(np.float32)
    lo = lo.astype(np.float32)
    cl = cl.astype(np.float32)
    vol = vol.astype(np.float32)

    O0 = float(op[0])
    H0 = float(hi[0])
    L0 = float(lo[0])
    C0 = float(cl[0])
    CD = float(cl[n - 1])

    hh = H0
    ll = L0
    for i in range(n):
        if float(hi[i]) > hh:
            hh = float(hi[i])
        if float(lo[i]) < ll:
            ll = float(lo[i])
    rng = hh - ll
    rng_eps = rng + 1e-8

    total = 0.0
    for i in range(n):
        total += float(vol[i])

    s = 0.0
    for i in range(n):
        s += float(hi[i]) - float(lo[i])
    atr_proxy = s / n

    # vwap array (cumulative, close-weighted)
    vwap_arr = np.zeros(n, dtype=np.float32)
    cum_cv = 0.0
    cum_v = 0.0
    for i in range(n):
        cum_cv += float(cl[i]) * float(vol[i])
        cum_v += float(vol[i])
        vwap_arr[i] = np.float32(cum_cv / (cum_v + 1e-8))
    vwap_d = float(vwap_arr[n - 1])

    # atr14_prev fallback used by the offline pipeline (see docstring)
    atr_5m_prev = float(prev_close) * 0.02
    sell_setup = 0.0

    # -- base early features (build_features.py; float64 like the reference) --
    out["gap_pct"] = (float(op64[0]) - float(prev_close)) / float(prev_close)
    out["first_bar_return"] = ((float(cl64[0]) - float(op64[0])) / float(op64[0])
                               if float(op64[0]) > 0 else 0.0)
    out["bar_ret_0"] = float(np.log(float(cl64[0]) / max(float(op64[0]), 1e-10)))
    out["bar_body_rng_0"] = ((float(cl64[0]) - float(op64[0])) /
                             (float(hi64[0]) - float(lo64[0]) + 1e-8))
    out["max_up_ret"] = (max(float(hi64[i]) for i in range(n)) - float(op64[0])) / max(float(op64[0]), 1e-10)
    out["max_down_ret"] = (min(float(lo64[i]) for i in range(n)) - float(op64[0])) / max(float(op64[0]), 1e-10)

    # -- EARLY_EXTRA ports (features_extra.py) --
    # 44 rally_strength_max : (max(C_i) - ll) / (hh - ll)
    cmax = CD
    for i in range(n):
        if float(cl[i]) > cmax:
            cmax = float(cl[i])
    out["rally_strength_max"] = np.float32((cmax - ll) / rng_eps)

    # 53 volume_weighted_price_position : (vwap_d - ll)/(hh - ll)
    out["volume_weighted_price_position"] = np.float32((vwap_d - ll) / rng_eps)

    # 54 net_volume_flow : sum((C-O)/(H-L) * V) / total
    nvf = 0.0
    for i in range(n):
        nvf += ((float(cl[i]) - float(op[i])) /
                (float(hi[i]) - float(lo[i]) + 1e-8)) * float(vol[i])
    out["net_volume_flow"] = np.float32(nvf / (total + 1e-8))

    # 55 early_body_momentum : sum(body_i)
    ebm = 0.0
    for i in range(n):
        ebm += (float(cl[i]) - float(op[i])) / (float(hi[i]) - float(lo[i]) + 1e-8)
    out["early_body_momentum"] = np.float32(ebm)

    # 92 limit_down_proximity_early
    limit_down_mult = 0.80 if is_20pct else 0.90
    out["limit_down_proximity_early"] = np.float32(
        (ll - float(prev_close) * limit_down_mult) /
        (float(prev_close) * limit_down_mult + 1e-8))

    # 97 demark_setup_reversal_early
    demark_sum = 0.0
    for i in range(n):
        ref = float(cl[i - 4]) if i >= 4 else float(prev_close)
        if float(cl[i]) < ref:
            demark_sum += 1.0
        elif float(cl[i]) > ref:
            demark_sum -= 1.0
    out["demark_setup_reversal_early"] = np.float32(demark_sum)

    # 114 early_order_flow_imbalance
    ofi = 0.0
    for i in range(n):
        rng_i = float(hi[i]) - float(lo[i]) + 1e-8
        ofi += ((float(cl[i]) - float(lo[i]) - (float(hi[i]) - float(cl[i]))) / rng_i) * float(vol[i])
    out["early_order_flow_imbalance"] = np.float32(ofi / (total + 1e-8))

    # 117 rbreaker_sell_setup_proximity_early (sell_setup=0, atr14_prev fallback)
    out["rbreaker_sell_setup_proximity_early"] = np.float32(
        (hh - sell_setup) / (atr_5m_prev + 1e-8))

    # 121 star50_limit_proximity_early
    limit_pct = 0.20 if is_20pct else 0.10
    upper_limit = float(prev_close) * (1.0 + limit_pct)
    lower_limit = float(prev_close) * (1.0 - limit_pct)
    dist_upper = (upper_limit - hh) / float(prev_close)
    dist_lower = (ll - lower_limit) / float(prev_close)
    out["star50_limit_proximity_early"] = np.float32((dist_lower - dist_upper) / limit_pct)

    # 127 morning_volume_weighted_momentum
    ret_mwm = (CD - O0) / (O0 + 1e-8)
    avg_vol_mwm = total / float(n) if n > 0 else 0.0
    vol_ratio_mwm = avg_vol_mwm / (float(exp_bar_vol) + 1e-8)
    val_mwm = ret_mwm * min(vol_ratio_mwm, 3.0) / 0.02
    out["morning_volume_weighted_momentum"] = np.float32(min(max(val_mwm, -1.0), 1.0))

    # 129 volume_weighted_momentum_acceleration
    if n >= 4:
        mid_vwma = n // 2
        vw_ret_first = 0.0
        vol_first_vwma = 0.0
        for i in range(mid_vwma):
            ret_i = (float(cl[i]) - float(op[i])) / (float(op[i]) + 1e-8)
            vw_ret_first += ret_i * float(vol[i])
            vol_first_vwma += float(vol[i])
        if vol_first_vwma > 0:
            vw_ret_first /= vol_first_vwma
        vw_ret_second = 0.0
        vol_second_vwma = 0.0
        for i in range(mid_vwma, n):
            ret_i = (float(cl[i]) - float(op[i])) / (float(op[i]) + 1e-8)
            vw_ret_second += ret_i * float(vol[i])
            vol_second_vwma += float(vol[i])
        if vol_second_vwma > 0:
            vw_ret_second /= vol_second_vwma
        val_vwma = (vw_ret_second - vw_ret_first) / (atr_proxy / (float(prev_close) + 1e-8) + 1e-8)
        out["volume_weighted_momentum_acceleration"] = np.float32(min(max(val_vwma, -1.0), 1.0))
    else:
        out["volume_weighted_momentum_acceleration"] = np.float32(0.0)

    # 130 volume_price_confirmation
    if n >= 3:
        sum_v = 0.0
        sum_b = 0.0
        sum_vv = 0.0
        sum_bb = 0.0
        sum_vb = 0.0
        for i in range(n):
            v_i = float(vol[i])
            rng_i = float(hi[i]) - float(lo[i]) + 1e-8
            b_i = (float(cl[i]) - float(op[i])) / rng_i
            sum_v += v_i
            sum_b += b_i
            sum_vv += v_i * v_i
            sum_bb += b_i * b_i
            sum_vb += v_i * b_i
        nf = float(n)
        cov_v = sum_vb - (sum_v * sum_b) / nf
        var_v = sum_vv - (sum_v * sum_v) / nf
        var_b = sum_bb - (sum_b * sum_b) / nf
        if var_v > 1e-8 and var_b > 1e-8:
            corr_v = cov_v / (math.sqrt(var_v) * math.sqrt(var_b) + 1e-8)
            out["volume_price_confirmation"] = np.float32(min(max(corr_v, -1.0), 1.0))
        else:
            out["volume_price_confirmation"] = np.float32(0.0)
    else:
        out["volume_price_confirmation"] = np.float32(0.0)

    # 134 early_late_momentum_divergence
    if n >= 4:
        early_mom = 0.0
        for i in range(2):
            rng_eld = float(hi[i]) - float(lo[i]) + 1e-8
            early_mom += (float(cl[i]) - float(op[i])) / rng_eld
        early_mom /= 2.0
        late_mom = 0.0
        for i in range(n - 2, n):
            rng_eld = float(hi[i]) - float(lo[i]) + 1e-8
            late_mom += (float(cl[i]) - float(op[i])) / rng_eld
        late_mom /= 2.0
        out["early_late_momentum_divergence"] = np.float32(min(max(late_mom - early_mom, -1.0), 1.0))
    else:
        out["early_late_momentum_divergence"] = np.float32(0.0)

    # 142 volatility_expansion_trend_vector
    if n >= 2:
        hh_vet = float(hi[0])
        ll_vet = float(lo[0])
        avg_r = 0.0
        for i in range(n):
            if float(hi[i]) > hh_vet:
                hh_vet = float(hi[i])
            if float(lo[i]) < ll_vet:
                ll_vet = float(lo[i])
            avg_r += float(hi[i]) - float(lo[i])
        avg_r = (avg_r / float(n)) + 1e-8
        total_r = hh_vet - ll_vet
        expansion = total_r / (avg_r * float(n) * 0.5)
        direction = (float(cl[n - 1]) - float(op[0])) / (total_r + 1e-8)
        out["volatility_expansion_trend_vector"] = np.float32(
            min(max(direction * min(expansion, 2.0), -1.0), 1.0))
    else:
        out["volatility_expansion_trend_vector"] = np.float32(0.0)

    # 144 opening_drive_thrust_ratio
    if n >= 3:
        hi_15 = max(float(hi[0]), max(float(hi[1]), float(hi[2])))
        lo_15 = min(float(lo[0]), min(float(lo[1]), float(lo[2])))
        rng_15 = hi_15 - lo_15 + 1e-8
        out["opening_drive_thrust_ratio"] = np.float32(
            min(max((float(cl[2]) - float(op[0])) / rng_15, -1.0), 1.0))
    else:
        out["opening_drive_thrust_ratio"] = np.float32(0.0)

    # 145 directional_volume_signature
    if n >= 2:
        bull_vol = 0.0
        bear_vol = 0.0
        bull_cnt = 0.0
        bear_cnt = 0.0
        for i in range(n):
            body = float(cl[i]) - float(op[i])
            v_i = float(vol[i])
            if body > 0:
                bull_vol += v_i
                bull_cnt += 1.0
            elif body < 0:
                bear_vol += v_i
                bear_cnt += 1.0
        avg_bull = bull_vol / (bull_cnt + 1e-8)
        avg_bear = bear_vol / (bear_cnt + 1e-8)
        total_avg = (bull_vol + bear_vol) / (float(n) + 1e-8)
        out["directional_volume_signature"] = np.float32(
            min(max((avg_bull - avg_bear) / (total_avg + 1e-8), -1.0), 1.0))
    else:
        out["directional_volume_signature"] = np.float32(0.0)

    # 146 body_size_progression
    if n >= 3:
        net_bsp = float(cl[n - 1]) - float(op[0])
        sx = 0.0
        sy = 0.0
        sxx = 0.0
        sxy = 0.0
        for i in range(n):
            body_bsp = (float(cl[i]) - float(op[i])) / (float(hi[i]) - float(lo[i]) + 1e-8)
            if net_bsp < 0:
                body_bsp = -body_bsp
            xi = float(i)
            sx += xi
            sy += body_bsp
            sxx += xi * xi
            sxy += xi * body_bsp
        denom = float(n) * sxx - sx * sx
        if abs(denom) > 1e-12:
            slope_bsp = (float(n) * sxy - sx * sy) / denom
            sign_bsp = 1.0 if net_bsp > 0 else -1.0
            out["body_size_progression"] = np.float32(min(max(sign_bsp * slope_bsp, -1.0), 1.0))
        else:
            out["body_size_progression"] = np.float32(0.0)
    else:
        out["body_size_progression"] = np.float32(0.0)

    # 149 vwap_close_divergence_trend
    if n >= 2:
        cum_pv = 0.0
        cum_v2 = 0.0
        above = 0.0
        total_dev = 0.0
        for i in range(n):
            p_i = (float(hi[i]) + float(lo[i]) + float(cl[i])) / 3.0
            v_i = float(vol[i])
            cum_pv += p_i * v_i
            cum_v2 += v_i
            vwap_i = cum_pv / (cum_v2 + 1e-8)
            dev = (float(cl[i]) - vwap_i) / (float(prev_close) * 0.005 + 1e-8)
            total_dev += dev
            if float(cl[i]) > vwap_i:
                above += 1.0
        consistency = max(above, float(n) - above) / float(n)
        avg_dev = total_dev / float(n)
        out["vwap_close_divergence_trend"] = np.float32(min(max(avg_dev * consistency, -1.0), 1.0))
    else:
        out["vwap_close_divergence_trend"] = np.float32(0.0)

    return out


