def compute_feature_value(feat, raw_feats, train_stats, ecdf_grids):
    """Raw value of one selected feature (base column or recipe combo)."""
    if feat.get("recipe"):
        return compute_recipe_value(feat["recipe"], raw_feats, train_stats, ecdf_grids)
    return float(raw_feats[feat["feature_name"]])


def compute_composite(cfg, raw_feats):
    """Sign-aligned z-score average composite + per-feature diagnostics."""
    train_stats = cfg["train_stats"]
    ecdf_grids = cfg["ecdf_grids"]
    combo_stats = cfg["combo_stats"]
    z_clip = float(cfg.get("z_clip", 3.0))

    zs = []
    detail = {}
    for feat in cfg["features"]:
        name = feat["feature_name"]
        val = compute_feature_value(feat, raw_feats, train_stats, ecdf_grids)
        st = combo_stats[name]
        sigma = float(st["sigma"])
        if sigma < 1e-12:
            sigma = 1.0
        z = (val - float(st["mu"])) / sigma
        if z > z_clip:
            z = z_clip
        elif z < -z_clip:
            z = -z_clip
        zs.append(float(feat["sign"]) * z)
        detail[name] = {"raw": val, "z": z, "sign": feat["sign"]}
    composite = float(np.mean(zs)) if zs else 0.0
    return composite, detail


def decide_side(composite, z_th_long, z_th_short):
    """'long' / 'short' / 'flat' from composite and thresholds."""
    if composite > z_th_long:
        return "long"
    if composite < -z_th_short:
        return "short"
    return "flat"


def trailing_stop_price(peak_price, frac_of_day_elapsed):
    """Time-decay trailing stop: allow STOPLOSS_TRAILING * (1 - t) drawdown
    from peak, tightening toward the peak as the day progresses.
    frac_of_day_elapsed in [0, 1] over the 10:00-14:35 holding window."""
    t = min(max(frac_of_day_elapsed, 0.0), 1.0)
    allowance = STOPLOSS_TRAILING * (1.0 - t)
    return peak_price * (1.0 - allowance)


