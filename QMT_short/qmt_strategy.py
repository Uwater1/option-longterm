def _std_col(raw_val, stats):
    """Standardize one raw component with baked train stats (float32)."""
    val = np.float32(raw_val)
    mean = np.float32(stats["mean"])
    std = np.float32(stats["std"])
    if std < 1e-7:
        std = np.float32(1.0)
    return (val - mean) / std


def _rank_col(raw_val, grid):
    """ECDF-rank one raw component with baked 128-knot grid (float32)."""
    v = np.float32(raw_val)
    xp = grid["xp"]
    fp = grid["fp"]
    n_knots = len(xp)
    if v <= xp[0]:
        return fp[0]
    if v >= xp[n_knots - 1]:
        return fp[n_knots - 1]
    lo_i = 0
    hi_i = n_knots - 1
    while hi_i - lo_i > 1:
        mid = (lo_i + hi_i) // 2
        if xp[mid] <= v:
            lo_i = mid
        else:
            hi_i = mid
    denom = xp[hi_i] - xp[lo_i]
    if denom < 1e-12:
        return fp[lo_i]
    t = (v - xp[lo_i]) / denom
    return fp[lo_i] + t * (fp[hi_i] - fp[lo_i])


def compute_recipe_value(recipe, raw_feats, train_stats, ecdf_grids):
    """Evaluate one combo recipe on raw feature values (single day)."""
    op = recipe["op"]

    def std(name):
        return _std_col(raw_feats[name], train_stats[name])

    def rnk(name):
        return _rank_col(raw_feats[name], ecdf_grids[name])

    if op == "min":
        return float(np.minimum(std(recipe["feature_a"]), std(recipe["feature_b"])))
    if op == "max":
        return float(np.maximum(std(recipe["feature_a"]), std(recipe["feature_b"])))
    if op == "diff" or op == "z_diff":
        return float(std(recipe["feature_a"]) - std(recipe["feature_b"]))
    if op == "z_sum":
        return float(std(recipe["feature_a"]) + std(recipe["feature_b"]))
    if op == "ratio":
        a = np.float32(raw_feats[recipe["feature_a"]])
        b = np.float32(raw_feats[recipe["feature_b"]])
        return float(a / (np.abs(b) + np.float32(1e-5)))
    if op == "mean":
        return float((std(recipe["feature_a"]) + std(recipe["feature_b"])) * np.float32(0.5))
    if op == "product":
        return float(std(recipe["feature_a"]) * std(recipe["feature_b"]))
    if op == "abs_diff":
        return float(np.abs(std(recipe["feature_a"]) - std(recipe["feature_b"])))
    if op == "rank_min":
        return float(np.minimum(rnk(recipe["feature_a"]), rnk(recipe["feature_b"])))
    if op == "rank_max":
        return float(np.maximum(rnk(recipe["feature_a"]), rnk(recipe["feature_b"])))
    if op == "clamp_diff":
        return float(np.clip(std(recipe["feature_a"]) - std(recipe["feature_b"]), -2.0, 2.0))
    if op == "sig_product":
        return float(np.sign(std(recipe["feature_a"])) * np.abs(std(recipe["feature_b"])))
    if op == "rel_diff":
        a = std(recipe["feature_a"])
        b = std(recipe["feature_b"])
        return float((a - b) / (np.abs(a) + np.abs(b) + np.float32(1e-5)))
    if op == "ifelse":
        cond = np.float32(raw_feats[recipe["feature_cond"]])
        thresh = np.float32(train_stats[recipe["feature_cond"]]["median"])
        return float(std(recipe["feature_a"]) if cond > thresh else std(recipe["feature_b"]))
    if op == "tri_mean" or op == "tri_z_mean":
        return float((std(recipe["feature_a"]) + std(recipe["feature_b"]) +
                      std(recipe["feature_c"])) / 3.0)
    if op == "tri_min":
        return float(min(std(recipe["feature_a"]), std(recipe["feature_b"]),
                         std(recipe["feature_c"])))
    if op == "tri_max":
        return float(max(std(recipe["feature_a"]), std(recipe["feature_b"]),
                         std(recipe["feature_c"])))
    if op == "tri_median":
        return float(np.median(np.array([std(recipe["feature_a"]),
                                         std(recipe["feature_b"]),
                                         std(recipe["feature_c"])], dtype=np.float32)))
    raise ValueError("Unknown recipe op: " + str(op))


